/** Pure helpers for browser recipes and the guardrail git hook (no vscode import, unit-tested). */

export interface Recipe {
  id: string;
  description: string;
  body: string;
}

/** Splits a .prompt.md file into front matter description and body. */
export function parseRecipe(id: string, text: string): Recipe {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/.exec(text.replace(/^\uFEFF/, ''));
  const description = m ? /^description:\s*(.+)$/m.exec(m[1])?.[1]?.trim() ?? id : id;
  return { id, description, body: (m ? m[2] : text).trim() };
}

export const HOOK_MARKER = '# agent-forge guardrail';

export function preCommitHook(cliPath: string): string {
  const cli = cliPath.replace(/\\/g, '/').replace(/"/g, '\\"');
  return [
    '#!/bin/sh',
    `${HOOK_MARKER} (generated by Agent Forge; delete this file to remove it)`,
    'command -v node >/dev/null 2>&1 || { echo "Agent Forge: node not found, skipping lint."; exit 0; }',
    `node "${cli}" lint . --fail-on error || {`,
    '  echo "Agent Forge: lint errors block this commit. Fix them, or bypass once with git commit --no-verify."',
    '  exit 1',
    '}',
    ''
  ].join('\n');
}
